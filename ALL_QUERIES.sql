

SELECT * FROM PIZZA_SALES;
-- KPI
--1.TOTAL REVENUE

SELECT SUM(TOTAL_PRICE) AS TOTAL_RENVENUE FROM PIZZA_SALES;

--2. TOTAL ORDERS
SELECT COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDER FROM PIZZA_SALES;

--3. AVERAGE ORDER VALUE
SELECT CAST(CAST(SUM(TOTAL_PRICE) AS DECIMAL(10,2)) /
CAST(COUNT(DISTINCT ORDER_ID) AS DECIMAL(10,2)) AS DECIMAL(10,2))
AS AVG_ORDER_VALUE
FROM PIZZA_SALES;

--4.TOTAL PIZZA SOLD
SELECT SUM(QUANTITY) AS TOTAL_PIZZA_SOLD FROM PIZZA_SALES;

--5. AVERAGE PIZZAS PER ORDER
SELECT CAST(CAST(SUM(QUANTITY) AS DECIMAL(10,2))/
CAST(COUNT(DISTINCT ORDER_ID) AS DECIMAL(10,2))
AS DECIMAL(10,2)) AS AVG_PIZZA_ORDER FROM PIZZA_SALES;


SELECT * FROM PIZZA_SALES;
--ANALYSIS
--1.Monthly Trend for Total Renvenue
SELECT
    TO_CHAR(oder_date, 'Month') AS month,
    SUM(total_price) AS total_revenue
FROM pizza_sales
GROUP BY TO_CHAR(oder_date, 'Month');


--2.Daily Trend for total orders
SELECT
    TO_CHAR(oder_date, 'day') AS day, count(distinct order_id) as total_orders
FROM pizza_sales
GROUP BY TO_CHAR(oder_date, 'day');

--3. percentage of sales by pizza category
SELECT PIZZA_CATEGORY, SUM(TOTAL_PRICE) AS TOTAL_REVENUE,
CAST(SUM(TOTAL_PRICE)*100/
(SELECT SUM(TOTAL_PRICE)FROM PIZZA_SALES) AS DECIMAL(10,2)) AS PCT
FROM PIZZA_SALES
GROUP BY PIZZA_CATEGORY;

--4.percentage of sales by pizze size
SELECT PIZZA_SIZE, SUM(TOTAL_PRICE) AS TOTAL_REVENUE,
CAST(SUM(TOTAL_PRICE)*100/
(SELECT SUM(TOTAL_PRICE)FROM PIZZA_SALES) AS DECIMAL(10,2)) AS PCT
FROM PIZZA_SALES
GROUP BY PIZZA_SIZE;

--5.total pizze sold by pizza size and category
SELECT PIZZA_SIZE,SUM(QUANTITY) AS TOTAL_PIZZA_SOLD
FROM PIZZA_SALES
GROUP BY PIZZA_SIZE;

SELECT PIZZA_CATEGORY,SUM(QUANTITY) AS TOTAL_PIZZA_SOLD
FROM PIZZA_SALES
GROUP BY PIZZA_CATEGORY;

--6.Renvenue by pizza name
SELECT PIZZA_NAME, SUM(TOTAL_PRICE) AS TOTAL_RENVENUE
FROM PIZZA_SALES
GROUP BY PIZZA_NAME
ORDER BY TOTAL_RENVENUE ASC
LIMIT 5;

--TOP & BOTTOM ANALYSIS
--1. Top Pizza by Renvenue
SELECT PIZZA_NAME, SUM(TOTAL_PRICE) AS TOTAL_RENVENUE
FROM PIZZA_SALES
GROUP BY PIZZA_NAME
ORDER BY TOTAL_RENVENUE DESC
LIMIT 5;

--2.Bottom Pizza Renvenue
SELECT PIZZA_NAME, SUM(TOTAL_PRICE) AS TOTAL_RENVENUE
FROM PIZZA_SALES
GROUP BY PIZZA_NAME
ORDER BY TOTAL_RENVENUE 
LIMIT 5;

--3. Top Pizza by orders
SELECT PIZZA_NAME, COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS
FROM PIZZA_SALES
GROUP BY PIZZA_NAME
ORDER BY TOTAL_ORDERS DESC
LIMIT 5;

--4. Top Pizza by orders
SELECT PIZZA_NAME, COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS
FROM PIZZA_SALES
GROUP BY PIZZA_NAME
ORDER BY TOTAL_ORDERS 
LIMIT 5;

--5. Top Pizza by Quantity sold
SELECT PIZZA_NAME, SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM PIZZA_SALES
GROUP BY PIZZA_NAME
ORDER BY TOTAL_QUANTITY_SOLD DESC
LIMIT 5;

--6. Bottom Pizza by Quantity sold
SELECT PIZZA_NAME, SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM PIZZA_SALES
GROUP BY PIZZA_NAME
ORDER BY TOTAL_QUANTITY_SOLD ASC
LIMIT 5;




